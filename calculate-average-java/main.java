public class ProjectAverageCalculator {
    public static void main(String[] args) {
        // Student's scores
        int score1 = 92;
        int score2 = 83;
        int score3 = 78;
        int score4 = 65;
        int score5 = 52;
        int score6 = 49;
        int score7 = 42;

        // Calculate the average score
        double average = (score1 + score2 + score3 + score4 + score5 + score6 + score7) / 7.0;

        // Print the result
        System.out.println("Average score: " + average);
    }
}
